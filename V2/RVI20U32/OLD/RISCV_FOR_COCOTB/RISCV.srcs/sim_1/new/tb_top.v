`timescale 1ns / 1ps

module tb_top;

    //========================================
    // CLOCK + RESET
    //========================================

    reg clk;
    reg rst;

    //========================================
    // DUT
    //========================================

    BASIC_wrapper dut (
        .clk(clk),
        .rst(rst)
    );

    //========================================
    // CLOCK 100 MHz
    //========================================

    initial begin
        clk = 1'b0;
    end

    always #5 clk = ~clk;

    //========================================
    // RESET
    //========================================

    initial begin
        rst = 1'b1;

        #100;

        rst = 1'b0;
    end

    //========================================
    // STOP SIMULATION
    //========================================

    initial begin
        #100000;

        $finish;
    end

endmodule