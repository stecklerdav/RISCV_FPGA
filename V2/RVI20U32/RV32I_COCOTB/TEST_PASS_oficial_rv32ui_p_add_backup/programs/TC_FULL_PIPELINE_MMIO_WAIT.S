.option norvc
.section .text
.global _start

.equ RAM_BASE,   0x00002000
.equ GPIO_BASE,  0x00003000
.equ UART_BASE,  0x00003010
.equ TIMER_BASE, 0x00003020

_start:
    # Bases
    lui  x1, 0x2          # RAM_BASE   = 0x2000
    lui  x2, 0x3          # GPIO_BASE  = 0x3000
    addi x3, x2, 0x10     # UART_BASE  = 0x3010
    addi x4, x2, 0x20     # TIMER_BASE = 0x3020

# ============================================================
# 1) STORE + LOAD + FORWARDING
# ============================================================

    addi x5, x0, 0x11
    sw   x5, 0(x1)

    addi x5, x0, 0x22
    sw   x5, 4(x1)

    addi x5, x0, 0x33
    sw   x5, 8(x1)

# ============================================================
# 2) LOAD-USE HAZARD
# ============================================================

    lw   x6, 0(x1)
    add  x7, x6, x6       # 0x22
    sw   x7, 12(x1)

    lw   x8, 4(x1)
    add  x9, x8, x8       # 0x44
    sw   x9, 16(x1)

# ============================================================
# 3) LOAD -> STORE DATA HAZARD
# ============================================================

    lw   x10, 8(x1)
    sw   x10, 20(x1)      # 0x33

# ============================================================
# 4) BRANCH DEPENDIENTE DE LOAD
# ============================================================

    lw   x11, 0(x1)
    addi x12, x0, 0x11
    beq  x11, x12, branch_ok

branch_fail:
    addi x13, x0, 0x55
    sw   x13, 24(x1)
    jal  x0, after_branch

branch_ok:
    addi x13, x0, 0x77
    sw   x13, 24(x1)

after_branch:

# ============================================================
# 5) GPIO MMIO WRITE
# ============================================================

    addi x14, x0, 0xA5
    sw   x14, 0(x2)

# ============================================================
# 6) UART MMIO WRITE: "OK\n"
# ============================================================

    addi x15, x0, 0x4F    # 'O'
    sw   x15, 0(x3)

    addi x15, x0, 0x4B    # 'K'
    sw   x15, 0(x3)

    addi x15, x0, 0x0A    # '\n'
    sw   x15, 0(x3)

# ============================================================
# 7) TIMER MMIO READS
# ============================================================

    lw   x16, 0(x4)
    sw   x16, 28(x1)

    lw   x17, 0(x4)
    sw   x17, 32(x1)

    lw   x18, 0(x4)
    sw   x18, 36(x1)

# ============================================================
# 8) LOOP / BRANCH STRESS
# RAM[10] = 5
# ============================================================

    addi x19, x0, 0       # counter
    addi x20, x0, 5       # limit

stress_loop:
    lw   x21, 40(x1)
    addi x21, x21, 1
    sw   x21, 40(x1)

    addi x19, x19, 1
    blt  x19, x20, stress_loop

# ============================================================
# 9) SIGNATURE FINAL
# RAM[11] = 0xCAFE0001
# ============================================================

    lui  x22, 0xCAFE0
    addi x22, x22, 1
    sw   x22, 44(x1)

end:
    jal x0, end
